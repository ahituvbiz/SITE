/* בורר יישוב משותף למחשבונים: שדה חיפוש + רשימה נגללת.
   מחזיר אובייקט עם get() - היישוב שנבחר ({name, pct, rate, cap, note}) או null כשנבחר "ללא". */
window.pensyaYishuvPicker = function (sel, search, onChange) {
  var D = window.PENSYA_YISHUVIM, list = [], current = null;
  D.groups.forEach(function (g) {
    g[2].split('|').forEach(function (n) { list.push({ name: n, pct: g[0], rate: g[0] / 100, cap: g[1], note: '' }); });
  });
  (D.special || []).forEach(function (s) {
    list.push({ name: s.name, pct: s.pct, rate: s.pct / 100, cap: s.cap, note: s.note || '' });
  });
  list.sort(function (a, b) { return a.name.localeCompare(b.name, 'he'); });
  list.forEach(function (y, i) { y.idx = i; });
  /* השוואה סלחנית: בלי גרשיים ומקפים, ו"קרית" כמו "קריית" */
  function norm(s) {
    return String(s).replace(/["'׳״’]/g, '').replace(/[-־]/g, ' ')
      .replace(/יי/g, 'י').replace(/\s+/g, ' ').trim();
  }
  function opt(value, text, disabled) {
    var o = document.createElement('option');
    o.value = value; o.textContent = text; if (disabled) o.disabled = true;
    return o;
  }
  function fill(q) {
    var nq = norm(q || ''), hits = nq ? list.filter(function (y) { return norm(y.name).indexOf(nq) >= 0; }) : list;
    while (sel.firstChild) sel.removeChild(sel.firstChild);
    sel.appendChild(opt('', 'ללא'));
    if (current && hits.indexOf(current) < 0) sel.appendChild(opt(String(current.idx), current.name));
    if (nq && !hits.length) sel.appendChild(opt('none', 'לא נמצא יישוב מזכה בשם הזה', true));
    hits.forEach(function (y) { sel.appendChild(opt(String(y.idx), y.name)); });
    sel.value = current ? String(current.idx) : '';
    return hits;
  }
  sel.addEventListener('change', function () {
    current = sel.value === '' ? null : (list[parseInt(sel.value, 10)] || null);
    if (onChange) onChange(current);
  });
  if (search) search.addEventListener('input', function () {
    var hits = fill(search.value);
    if (hits.length === 1 && current !== hits[0]) {
      current = hits[0]; sel.value = String(current.idx);
      if (onChange) onChange(current);
    }
  });
  fill('');
  return {
    get: function () { return current; },
    count: list.length,
    describe: function (y) { return y ? y.pct + '% עד ' + y.cap.toLocaleString('en-US') + ' ₪' : 'ללא'; }
  };
};
